// Scans module/**/*.mjs for every attributeKey literal passed to getInheritableAttribute
// (and similar call sites) and writes the deduped, sorted result to
// module/common/known-attribute-keys.mjs. That file powers the autocomplete <datalist> on
// the generic Changes-tab editor (templates/change/change.hbs) — a suggestion list only,
// free text still works, so this doesn't need to be exhaustive to be useful.
//
// Usage: node scripts/extract-attribute-keys.mjs
import {readFileSync, writeFileSync, readdirSync} from "node:fs";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const MODULE_DIR = path.join(REPO_ROOT, "module");
const OUT_FILE = path.join(REPO_ROOT, "module", "common", "known-attribute-keys.mjs");

const ATTRIBUTE_KEY_PATTERN = /attributeKey:\s*(\[[^\]]*\]|["'][^"']*["'])/g;
const STRING_LITERAL_PATTERN = /["']([^"']+)["']/g;

function collectMjsFiles(dir) {
    const files = [];
    for (const entry of readdirSync(dir, {withFileTypes: true})) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...collectMjsFiles(full));
        } else if (entry.isFile() && entry.name.endsWith(".mjs")) {
            files.push(full);
        }
    }
    return files;
}

function extractKeysFromFile(filePath) {
    const content = readFileSync(filePath, "utf8");
    const keys = [];
    for (const match of content.matchAll(ATTRIBUTE_KEY_PATTERN)) {
        for (const literal of match[1].matchAll(STRING_LITERAL_PATTERN)) {
            keys.push(literal[1]);
        }
    }
    return keys;
}

const keys = new Set();
for (const file of collectMjsFiles(MODULE_DIR)) {
    for (const key of extractKeysFromFile(file)) {
        keys.add(key);
    }
}

const sorted = [...keys].sort((a, b) => a.localeCompare(b));

const output = `// AUTO-GENERATED by scripts/extract-attribute-keys.mjs — do not hand-edit, re-run the
// script instead. Every attributeKey literal found across module/**/*.mjs at generation
// time, deduped and sorted. Powers the autocomplete <datalist> on the generic Changes-tab
// editor; not exhaustive, not a validation allow-list — free text keys still work fine.

export const KNOWN_ATTRIBUTE_KEYS = ${JSON.stringify(sorted, null, 4)};
`;

writeFileSync(OUT_FILE, output);
console.log(`Wrote ${sorted.length} known attribute keys to ${path.relative(REPO_ROOT, OUT_FILE)}`);
